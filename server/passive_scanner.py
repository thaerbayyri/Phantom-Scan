import subprocess
import os
import time
import glob
import hashlib

class PassiveScanner:
    """
    Standalone Python reference demonstrating authorized, privacy-compliant passive scanning.
    Strictly uses '--output-format csv' to prevent handshake captures (no .cap/.pcap files).
    """
    def __init__(self, interface="wlan0"):
        self.interface = interface
        self.scan_dir = os.path.join(os.getcwd(), "scans")
        os.makedirs(self.scan_dir, exist_ok=True)
        self.process = None
        self.unique_hashed_macs = set()

    def start_scan(self):
        prefix = os.path.join(self.scan_dir, f"env_scan_{int(time.time())}")
        
        # Security Constraint: --output-format csv ONLY to prevent .cap generation
        cmd = [
            "airodump-ng", 
            "--output-format", "csv", 
            "--write", prefix, 
            self.interface
        ]
        
        print(f"[PassiveScanner] Starting safe telemetry gathering on {self.interface}...")
        # shell=False prevents command injection vulnerabilities
        self.process = subprocess.Popen(cmd, shell=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        
        # In this Python reference script we just wait a bit to simulate background execution
        try:
            time.sleep(10)
        except KeyboardInterrupt:
            pass
        finally:
            self.stop_scan()
            self._cleanup(prefix)

    def stop_scan(self):
        if self.process:
            self.process.terminate()
            self.process.wait()
            print("[PassiveScanner] Stopped gathering telemetry.")
            
    def _simulate_gdpr_hash(self, raw_mac: str):
        """
        Demonstrates instantly hashing MAC addresses in memory to maintain GDPR compliance
        and discard PII while still enabling cardinality counting.
        """
        return hashlib.sha256(raw_mac.encode()).hexdigest()

    def _cleanup(self, prefix):
        # Clean up the CSV files generated by airodump-ng
        base_name = os.path.basename(prefix)
        for f in glob.glob(os.path.join(self.scan_dir, f"{base_name}*")):
            try:
                os.remove(f)
                print(f"[PassiveScanner] Cleaned up temporary telemetry file: {f}")
            except Exception as e:
                print(f"[PassiveScanner] Failed to clean up {f}: {e}")

if __name__ == "__main__":
    scanner = PassiveScanner()
    scanner.start_scan()
